"""Static arbitrage checks for implied volatility slices and surfaces.

An arbitrage-free surface is one you could have generated by a genuine
risk-neutral density. Two classic failure modes:

**Butterfly (strike) arbitrage** — within a single expiry, the risk-neutral
density must be non-negative. Equivalently the call price must be convex in
strike, ``d2C/dK2 >= 0``. In total-variance terms Gatheral's g-function must be
non-negative everywhere:

    g(k) >= 0   for all k  =>  density >= 0

**Calendar (maturity) arbitrage** — total variance must be non-decreasing in
time to expiry at fixed log-moneyness:

    w(k, T2) >= w(k, T1)   for T2 > T1

otherwise a calendar spread is free money. Note this is stated in *total*
variance: variance can perfectly well fall with maturity, total variance cannot.

Buttoned-up versions of these conditions also require ``w >= 0`` and the correct
wing behaviour as ``|k| -> inf``; the checks below cover the practical
diagnostics that catch bad fits on real quotes.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from optlab.surface.svi import SVIParams, gatheral_g


@dataclass(frozen=True)
class ArbitrageReport:
    """Result of an arbitrage scan.

    ``is_arbitrage_free`` is the headline; ``worst_value`` is the most negative
    value found (negative means arbitrage) and ``worst_k`` where it happened.
    ``curve`` holds the scanned values as ``(k, value)`` so a notebook can plot
    it without recomputing.
    """

    kind: str
    is_arbitrage_free: bool
    worst_value: float
    worst_k: float
    n_points: int
    tolerance: float
    curve: tuple[np.ndarray, np.ndarray]

    def summary(self) -> str:
        status = "arbitrage-free" if self.is_arbitrage_free else "ARBITRAGE"
        return (
            f"{self.kind}: {status} | worst {self.worst_value:+.3e} at k={self.worst_k:+.3f} "
            f"({self.n_points} points, tol {self.tolerance:.0e})"
        )


def scan_butterfly(
    params: SVIParams,
    k_min: float = -1.0,
    k_max: float = 1.0,
    n: int = 201,
    tolerance: float = 1e-8,
) -> ArbitrageReport:
    """Scan Gatheral's g-function over ``[k_min, k_max]``.

    Also checks that total variance is positive (``w >= 0``), which an
    unconstrained fit can violate far in the wings.
    """
    k = np.linspace(k_min, k_max, n)
    g = gatheral_g(params, k)
    w = np.asarray(params.total_variance(k), dtype=float)
    # Report the worst of the two conditions: negative g or negative variance.
    finite = np.isfinite(g)
    combined = np.where(finite, g, -np.inf)
    combined = np.minimum(combined, w)
    worst_value = float(np.min(combined))
    worst_k = float(k[int(np.argmin(combined))])
    return ArbitrageReport(
        kind="butterfly",
        is_arbitrage_free=bool(worst_value >= -tolerance),
        worst_value=worst_value,
        worst_k=worst_k,
        n_points=int(n),
        tolerance=tolerance,
        curve=(k, combined),
    )


def scan_calendar(
    early: SVIParams,
    late: SVIParams,
    k_min: float = -1.0,
    k_max: float = 1.0,
    n: int = 201,
    tolerance: float = 1e-10,
) -> ArbitrageReport:
    """Check ``w_late(k) - w_early(k) >= 0`` across a range of log-moneynesses.

    ``early`` and ``late`` must be slices for the same underlying with
    ``T_late > T_early``; the function only sees total variance, so the caller
    is responsible for the ordering.
    """
    k = np.linspace(k_min, k_max, n)
    diff = np.asarray(late.total_variance(k) - early.total_variance(k), dtype=float)
    worst_value = float(np.min(diff))
    worst_k = float(k[int(np.argmin(diff))])
    return ArbitrageReport(
        kind="calendar",
        is_arbitrage_free=bool(worst_value >= -tolerance),
        worst_value=worst_value,
        worst_k=worst_k,
        n_points=int(n),
        tolerance=tolerance,
        curve=(k, diff),
    )


def check_surface(
    params_by_expiry: list[SVIParams],
    maturities: list[float],
    k_min: float = -1.0,
    k_max: float = 1.0,
    n: int = 201,
) -> list[ArbitrageReport]:
    """Run every butterfly check plus each adjacent calendar check.

    Returns one report per slice followed by one per adjacent expiry pair, so a
    notebook can print them all and a test can assert on ``is_arbitrage_free``.
    """
    if len(params_by_expiry) != len(maturities):
        raise ValueError("params_by_expiry and maturities must have the same length")
    order = np.argsort(np.asarray(maturities, dtype=float))
    params_sorted = [params_by_expiry[i] for i in order]

    reports = [scan_butterfly(p, k_min, k_max, n) for p in params_sorted]
    reports += [
        scan_calendar(params_sorted[i], params_sorted[i + 1], k_min, k_max, n)
        for i in range(len(params_sorted) - 1)
    ]
    return reports


def is_arbitrage_free(reports: list[ArbitrageReport]) -> bool:
    """True when every report in the list passed."""
    return all(r.is_arbitrage_free for r in reports)


def repair_butterfly(
    params: SVIParams,
    k_min: float = -1.0,
    k_max: float = 1.0,
    n: int = 201,
    max_rounds: int = 40,
) -> SVIParams:
    """Nudge ``b`` down until the butterfly check passes.

    A blunt but effective repair: lowering the wing slope ``b`` while keeping the
    vertex scaling roughly constant reduces ``g``'s variation. Returns the
    original parameters if it cannot find a clean set, so callers should re-check
    with :func:`scan_butterfly` rather than assume success.
    """
    current = params
    for _ in range(max_rounds):
        if scan_butterfly(current, k_min, k_max, n).is_arbitrage_free:
            return current
        b = current.b * 0.95
        if b <= 1e-8:
            break
        # Keep sigma*b roughly constant so the wings do not collapse.
        scale = current.b / b
        current = SVIParams(
            a=current.a,
            b=b,
            rho=current.rho,
            m=current.m,
            sigma=min(current.sigma * np.sqrt(scale), 5.0),
        )
    return current
